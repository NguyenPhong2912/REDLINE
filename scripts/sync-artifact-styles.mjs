import fs from "node:fs";
import postcss from "postcss";

// Only extract CSS from the checked-in design. Never execute the canvas logic:
// its sample transactions and metrics are not production application state.
const dir = "design/astral-depth/artboards";
const names = {
  Main: "protocol",
  Marketplace: "marketplace",
  Agents: "agents",
  Guardrails: "guardrails",
  Treasury: "treasury",
  Audit: "audit",
  Analytics: "analytics",
  Settings: "settings",
  Copilot: "copilot",
  Models: "models",
  Profile: "profile",
};
const sources = Object.keys(names).map(
  (n) =>
    fs
      .readFileSync(`${dir}/${n}.dc.html`, "utf8")
      .match(/<style>([\s\S]*?)<\/style>/)[1],
);
const marker = sources[0].indexOf("\n  .app{--pg:");
let css = sources[0].slice(0, marker);
css = css.replace(/\.sc-interp\{[^}]+\}/g, "");
for (const [i, [name, route]] of Object.entries(names).entries()) {
  const root = postcss.parse(sources[i].slice(marker));
  root.walkRules((rule) => {
    if (rule.parent.type === "atrule" && /keyframes/.test(rule.parent.name))
      return;
    rule.selectors = rule.selectors.map((selector) =>
      selector.trim() === ".app"
        ? `[data-route="${route}"]`
        : `[data-route="${route}"] ${selector}`,
    );
  });
  css += `\n/* ${name}: exact artboard styles, scoped to this route. */\n${root.toString()}\n`;
}
fs.writeFileSync(
  "src/styles/artifact-source.css",
  "/* Generated by scripts/sync-artifact-styles.mjs from the supplied artifact. */\n" +
    css.replace(/[ \t]+$/gm, "").trimEnd() + "\n",
);
